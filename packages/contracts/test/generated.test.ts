import { mkdtempSync, readdirSync, readFileSync, rmSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { describe, expect, test } from "vitest";
import {
  DOCUMENT_GROUPS,
  GENERATED_DIRS,
  GENERATED_SWIFT_FILE,
  generate,
  PACKAGE_DIR,
  SWIFT_DOCUMENTS,
  writeGenerated,
} from "../scripts/codegen.ts";
import {
  RECORDING_SCHEMA_FILES,
  RECORDING_SET_SCHEMA_FILES,
  RECORDING_SWIFT_FILES,
} from "../src/recording.ts";
import { ALL_SCHEMA_FILES } from "./schemas.ts";

// quicktype and Prettier take a few seconds on a cold start.
const TIMEOUT_MS = 60_000;

describe("generated code", () => {
  test(
    "is up to date with the schemas (run `pnpm gen` if this fails)",
    async () => {
      const outDir = mkdtempSync(join(tmpdir(), "usg-contracts-gen-"));
      try {
        const files = await writeGenerated(outDir);
        for (const dir of GENERATED_DIRS) {
          expect(readdirSync(join(PACKAGE_DIR, dir)).sort(), dir).toEqual(
            readdirSync(join(outDir, dir)).sort(),
          );
        }
        for (const file of files) {
          const committed = readFileSync(join(PACKAGE_DIR, file.path), "utf8");
          expect(committed, `${file.path} is stale`).toBe(
            readFileSync(join(outDir, file.path), "utf8"),
          );
        }
      } finally {
        rmSync(outDir, { recursive: true, force: true });
      }
    },
    TIMEOUT_MS,
  );

  test(
    "is deterministic, with LF endings and no machine-specific text",
    async () => {
      const [first, second] = await Promise.all([generate(), generate()]);
      expect(second).toEqual(first);
      for (const file of first ?? []) {
        expect(file.content, file.path).not.toContain("\r");
        expect(file.content, file.path).not.toContain(PACKAGE_DIR);
        expect(file.content.startsWith("// Generated by packages/contracts/scripts/gen.ts")).toBe(
          true,
        );
      }
    },
    TIMEOUT_MS,
  );
});

describe("which documents get which output", () => {
  test("every schema except a defs file is a document of one group, and only the recording reuses another's", () => {
    for (const group of DOCUMENT_GROUPS) {
      const schemas = group.documents.map((d) => d.schema);
      expect(new Set(schemas).size, group.key).toBe(schemas.length);
    }
    const owned = DOCUMENT_GROUPS.flatMap((group) =>
      group.documents
        .map((d) => d.schema)
        .filter((schema) => group.key !== "recording" || schema.startsWith("recording/")),
    );
    expect(new Set(owned).size).toBe(owned.length);
    expect([...owned].sort()).toEqual(
      ALL_SCHEMA_FILES.filter((file) => !file.endsWith("/defs.schema.json")).sort(),
    );
    // The recording reuses only the capture bundle's line schemas.
    const recording = DOCUMENT_GROUPS.find((group) => group.key === "recording");
    for (const document of recording?.documents ?? []) {
      expect(document.schema).toMatch(/^recording\/|^capture-bundle\/[a-z-]+-line\.schema\.json$/);
    }
  });

  test("only the capture bundle's documents and the recording files Swift writes get Swift types", () => {
    expect(SWIFT_DOCUMENTS.map((d) => d.schema)).toEqual([
      ...DOCUMENT_GROUPS.flatMap((g) => g.documents)
        .map((d) => d.schema)
        .filter((schema) => schema.startsWith("capture-bundle/"))
        .filter((schema, index, all) => all.indexOf(schema) === index),
      ...RECORDING_SWIFT_FILES.map(
        (name) => ({ ...RECORDING_SCHEMA_FILES, ...RECORDING_SET_SCHEMA_FILES })[name],
      ),
    ]);
  });

  test(
    "Contracts.swift has no snapshot, diff or PC-only recording types",
    async () => {
      const swift = (await generate()).find((file) => file.path === GENERATED_SWIFT_FILE);
      for (const name of [
        "IndoorSnapshot",
        "LatestPointer",
        "StatusOverlay",
        "ChangeSetDiff",
        "VenueRow",
        "BoundaryLine",
        "RecordingImport",
      ]) {
        expect(swift?.content).not.toContain(name);
      }
      expect(swift?.content).toContain("struct CaptureManifest");
      expect(swift?.content).toContain("struct RecordingManifest");
      expect(swift?.content).toContain("struct ExportParts");
    },
    TIMEOUT_MS,
  );
});

describe("the package entry point", () => {
  // Environment neutrality itself (no Node globals or node: imports) is checked by the
  // typecheck: `tsc -p tsconfig.neutral.json` compiles the . entry with no Node types. This test
  // checks what tsc can't: the . entry imports only this package's own files, never Ajv or the
  // Node-only bundle validator.
  test("imports only its own files, and never reaches the bundle validator", () => {
    const entry = join(PACKAGE_DIR, "src", "index.ts");
    const seen = new Set<string>();
    const pending = [entry];
    while (pending.length > 0) {
      const file = pending.pop() ?? "";
      if (seen.has(file)) continue;
      seen.add(file);
      const text = readFileSync(file, "utf8");
      // Static (from "x"), side-effect (import "x") and dynamic (import("x")) imports.
      const specifiers = [...text.matchAll(/\b(?:from|import)\s*\(?\s*"([^"]+)"/g)].map(
        (match) => match[1] ?? "",
      );
      for (const specifier of specifiers) {
        expect(specifier, `${file} imports ${specifier}`).toMatch(/^\.\.?\//);
        pending.push(join(dirname(file), specifier));
      }
    }
    expect(seen.size).toBeGreaterThan(1);
    for (const file of seen) {
      expect(file, "the . entry reaches the bundle validator").not.toContain("bundle-validator");
      expect(file, "the . entry reaches the Ajv validators").not.toContain("validators");
      expect(file, "the . entry reaches the schema files (node:fs)").not.toContain("schema-files");
    }
  });

  test("the neutral typecheck compiles the . entry without Node types", () => {
    const config = JSON.parse(
      readFileSync(join(PACKAGE_DIR, "tsconfig.neutral.json"), "utf8"),
    ) as Record<string, unknown>;
    expect(config["files"]).toEqual(["src/index.ts"]);
    expect(config["compilerOptions"]).toMatchObject({
      types: [],
      noUncheckedSideEffectImports: true,
    });
    const scripts = (
      JSON.parse(readFileSync(join(PACKAGE_DIR, "package.json"), "utf8")) as {
        scripts: Record<string, string>;
      }
    ).scripts;
    expect(scripts["typecheck"]).toContain("tsc -p tsconfig.neutral.json");
  });
});

describe("package exports", () => {
  const require = createRequire(import.meta.url);

  test("the . entry is src/index.ts", () => {
    expect(require.resolve("@usg/contracts")).toBe(join(PACKAGE_DIR, "src", "index.ts"));
  });

  test("the validators entry is src/validators.ts", () => {
    expect(require.resolve("@usg/contracts/validators")).toBe(
      join(PACKAGE_DIR, "src", "validators.ts"),
    );
  });

  test("the bundle-validator entry is src/bundle-validator/index.ts", () => {
    expect(require.resolve("@usg/contracts/bundle-validator")).toBe(
      join(PACKAGE_DIR, "src", "bundle-validator", "index.ts"),
    );
  });

  test("schemas/* resolves to the schema files", () => {
    expect(require.resolve("@usg/contracts/schemas/capture-bundle/manifest.schema.json")).toBe(
      join(PACKAGE_DIR, "schemas", "capture-bundle", "manifest.schema.json"),
    );
  });
});
